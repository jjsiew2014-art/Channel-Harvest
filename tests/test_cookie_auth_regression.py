"""
test_cookie_auth_regression.py
Comprehensive regression tests for Custom Cookie File authentication,
MozillaCookieJar API compatibility, and diagnostic semantics in Channel Harvest.

Covers the 9 required regression specifications:
1. A valid Mozilla/Netscape cookie file loads successfully.
2. The code no longer calls unsupported methods on MozillaCookieJar.
3. An internal AttributeError is reported as an internal error, not a confirmed YouTube rejection.
4. Cookie parsing success is distinguished from verified session authentication.
5. A valid cookie file reaches the expected yt-dlp configuration.
6. Malformed and expired cookie files produce appropriate diagnostic messages.
7. Public YouTube downloads remain usable without cookies.
8. Existing HTTP 403 recovery and queue continuation remain functional.
9. TikTok behavior remains unchanged and Douyin remains frozen.
"""

import http.cookiejar
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch, MagicMock

from yt_dlp import YoutubeDL

from core.models import DownloadSettings, VideoItem, VideoStatus
from core.platform import PlatformRegistry
from core.platform.youtube import YouTubeAdapter
from core.platform.tiktok import TikTokAdapter
from core.platform.douyin import DouyinAdapter
from core.platform.auth import PlatformAuthConfig
from core.error_classifier import ErrorClassifier, ErrorCategory
from downloader.auth_checker import (
    AuthChecker,
    AuthStatusCode,
    AuthStage,
    AuthTestResult,
    validate_cookie_file,
)
from downloader.ytdlp_engine import YtDlpEngine


class TestCookieAuthRegression(unittest.TestCase):
    """Deterministic regression tests for YouTube cookie authentication."""

    def setUp(self):
        # Create a valid Netscape cookie file with authentic YouTube session cookies
        self.temp_dir = tempfile.TemporaryDirectory()
        self.cookie_file_path = Path(self.temp_dir.name) / "youtube_cookies.txt"
        self.cookie_file_content = (
            "# Netscape HTTP Cookie File\n"
            "# https://curl.se/docs/http-cookies.html\n"
            "# This file was generated by an exported session.\n"
            ".youtube.com\tTRUE\t/\tTRUE\t2147483647\tLOGIN_INFO\ta_valid_login_info_token\n"
            ".youtube.com\tTRUE\t/\tTRUE\t2147483647\tSID\ta_valid_sid_token\n"
            ".youtube.com\tTRUE\t/\tTRUE\t2147483647\tPREF\tf1=50000000\n"
        )
        self.cookie_file_path.write_text(self.cookie_file_content, encoding="utf-8")

    def tearDown(self):
        self.temp_dir.cleanup()

    # -------------------------------------------------------------------------
    # 1. A valid Mozilla/Netscape cookie file loads successfully
    # -------------------------------------------------------------------------
    def test_1_valid_netscape_cookie_file_loads(self):
        """Verify that a valid Netscape cookie file parses completely without errors."""
        jar, err = AuthChecker._load_cookie_file(self.cookie_file_path)
        self.assertEqual(err, "")
        self.assertIsNotNone(jar)
        self.assertEqual(len(jar), 3)

        # Inspect YouTube cookies
        yt_cookies, has_session = AuthChecker._inspect_youtube_cookies(jar)
        self.assertEqual(len(yt_cookies), 3)
        self.assertTrue(has_session)

        # Non-destructive synchronous validation
        res = validate_cookie_file(str(self.cookie_file_path))
        self.assertTrue(res["is_valid"])
        self.assertEqual(res["cookie_count"], 3)
        self.assertEqual(res["youtube_cookie_count"], 3)
        self.assertTrue(res["has_session"])
        self.assertEqual(res["status_code"], AuthStatusCode.COOKIE_FILE_VALID)

    # -------------------------------------------------------------------------
    # 2. The code no longer calls unsupported methods on MozillaCookieJar
    # -------------------------------------------------------------------------
    def test_2_no_unsupported_methods_called_on_mozilla_cookie_jar(self):
        """
        Verify that passing a standard library MozillaCookieJar into _verify_live_request
        does not invoke missing methods (get_cookie_header) on MozillaCookieJar,
        and that yt-dlp receives a compatible cookie jar.
        """
        std_jar = http.cookiejar.MozillaCookieJar()
        cookie = http.cookiejar.Cookie(
            version=0,
            name="LOGIN_INFO",
            value="token_123",
            port=None,
            port_specified=False,
            domain=".youtube.com",
            domain_specified=True,
            domain_initial_dot=True,
            path="/",
            path_specified=True,
            secure=True,
            expires=2147483647,
            discard=False,
            comment=None,
            comment_url=None,
            rest={},
        )
        std_jar.set_cookie(cookie)

        # Standard MozillaCookieJar explicitly lacks get_cookie_header
        self.assertFalse(hasattr(std_jar, "get_cookie_header"))

        # Verify that _verify_live_request adapts std_jar without raising AttributeError
        captured_has_method = False

        def fake_extract_info(ydl_instance, url, download=False, process=False):
            nonlocal captured_has_method
            # Check that ydl_instance.cookiejar has get_cookie_header
            captured_has_method = hasattr(ydl_instance.cookiejar, "get_cookie_header")
            return {"title": "Test Video"}

        with patch.object(YoutubeDL, "extract_info", fake_extract_info):
            ok, err = AuthChecker._verify_live_request(jar=std_jar)
            self.assertTrue(ok)
            self.assertEqual(err, "")
            self.assertTrue(captured_has_method)

    # -------------------------------------------------------------------------
    # 3. An internal AttributeError is reported as internal error, not YouTube rejection
    # -------------------------------------------------------------------------
    def test_3_internal_attribute_error_reported_as_internal_error(self):
        """
        Verify that an internal AttributeError during live verification is reported
        as an internal application diagnostic error, NOT a confirmed YouTube rejection.
        """
        attr_err = AttributeError("'MozillaCookieJar' object has no attribute 'get_cookie_header'")

        with patch.object(YoutubeDL, "extract_info", side_effect=attr_err):
            result = AuthChecker.test_authentication(
                "custom_file",
                custom_cookie_path=str(self.cookie_file_path),
            )

            # Verification failed due to internal error
            self.assertFalse(result.success)
            self.assertEqual(result.stage, AuthStage.YOUTUBE_REQUEST)
            self.assertEqual(result.status_code, AuthStatusCode.INTERNAL_ERROR)

            # CRITICAL: has_session must be False and diagnostic report must say "Session Authenticated: No"
            self.assertFalse(result.has_session)
            self.assertNotIn("YouTube rejected login", result.reason)
            self.assertNotIn("YouTube rejected the authenticated request", result.reason)
            self.assertIn("internal", result.reason.lower())
            self.assertIn("AttributeError", result.technical_error)

            # Check formatted report
            report = result.to_diagnostic_report()
            self.assertIn("Session Authenticated:  No", report)
            self.assertIn("Status Code:            INTERNAL_ERROR", report)
            self.assertIn("Technical Error:", report)
            self.assertIn("AttributeError", report)

    # -------------------------------------------------------------------------
    # 4. Cookie parsing success is distinguished from verified session authentication
    # -------------------------------------------------------------------------
    def test_4_cookie_parsing_distinguished_from_verified_session(self):
        """
        Verify that:
        - Parsed session cookies in file does NOT mean verified authenticated session.
        - Only a successful verification request with session cookies yields Session Authenticated: Yes.
        - A failed verification yields Session Authenticated: No even when session cookies exist.
        - A successful verification with only anonymous cookies yields Session Authenticated: No.
        """
        # Case A: Static file validation indicates file contains session tokens, but is not verified
        val = validate_cookie_file(str(self.cookie_file_path))
        self.assertTrue(val["is_valid"])
        self.assertEqual(val["status_code"], AuthStatusCode.COOKIE_FILE_VALID)
        self.assertNotEqual(val["status_code"], AuthStatusCode.YOUTUBE_SESSION_AUTHENTICATED)

        # Case B: Live verification fails (e.g. YouTube returns 401 Unauthorized)
        with patch.object(AuthChecker, "_verify_live_request", return_value=(False, "YouTube rejected login: HTTP Error 401: Unauthorized")):
            res_fail = AuthChecker.test_authentication("custom_file", custom_cookie_path=str(self.cookie_file_path))
            self.assertFalse(res_fail.success)
            self.assertFalse(res_fail.has_session)
            self.assertEqual(res_fail.status_code, AuthStatusCode.AUTHENTICATION_REQUIRED)
            report_fail = res_fail.to_diagnostic_report()
            self.assertIn("Session Authenticated:  No", report_fail)

        # Case C: Live verification succeeds with session cookies -> Authenticated!
        with patch.object(AuthChecker, "_verify_live_request", return_value=(True, "")):
            res_ok = AuthChecker.test_authentication("custom_file", custom_cookie_path=str(self.cookie_file_path))
            self.assertTrue(res_ok.success)
            self.assertTrue(res_ok.has_session)
            self.assertEqual(res_ok.status_code, AuthStatusCode.YOUTUBE_SESSION_AUTHENTICATED)
            report_ok = res_ok.to_diagnostic_report()
            self.assertIn("Session Authenticated:  Yes", report_ok)

        # Case D: Live verification succeeds but file ONLY had anonymous cookies (no LOGIN_INFO/SID)
        anon_file = Path(self.temp_dir.name) / "anon_cookies.txt"
        anon_file.write_text(
            "# Netscape HTTP Cookie File\n"
            ".youtube.com\tTRUE\t/\tTRUE\t2147483647\tPREF\tf1=50000000\n",
            encoding="utf-8",
        )
        with patch.object(AuthChecker, "_verify_live_request", return_value=(True, "")):
            res_anon = AuthChecker.test_authentication("custom_file", custom_cookie_path=str(anon_file))
            self.assertTrue(res_anon.success)
            self.assertFalse(res_anon.has_session)
            self.assertEqual(res_anon.status_code, AuthStatusCode.COOKIE_FILE_VALID)
            report_anon = res_anon.to_diagnostic_report()
            self.assertIn("Session Authenticated:  No", report_anon)

    # -------------------------------------------------------------------------
    # 5. A valid cookie file reaches the expected yt-dlp configuration
    # -------------------------------------------------------------------------
    def test_5_valid_cookie_file_reaches_ytdlp_configuration(self):
        """
        Verify that a configured custom cookie file reaches yt-dlp option dictionaries
        in build_base_ydl_opts, YouTubeAdapter, and auxiliary managers.
        """
        settings = DownloadSettings()
        settings.auth_method = "custom_file"
        settings.browser_cookies = "custom_file"
        settings.custom_cookie_file = str(self.cookie_file_path)

        # 1. YouTubeAdapter resolves PlatformAuthConfig with cookie_file
        adapter = YouTubeAdapter()
        auth_config = adapter.get_auth_config(settings=settings)
        self.assertTrue(auth_config.is_active)
        self.assertEqual(auth_config.auth_method, "custom_file")
        self.assertEqual(Path(auth_config.cookie_file).resolve(), self.cookie_file_path.resolve())

        # 2. build_base_ydl_opts sets ydl_opts["cookiefile"]
        ydl_opts = YtDlpEngine.build_base_ydl_opts(settings=settings)
        self.assertIn("cookiefile", ydl_opts)
        self.assertEqual(Path(ydl_opts["cookiefile"]).resolve(), self.cookie_file_path.resolve())

        # 3. SettingsManager fallback when caller passes settings dict without custom_cookie_file
        from core.settings import SettingsManager
        sm = SettingsManager()
        sm.set("auth_method", "custom_file")
        sm.set("custom_cookie_file", str(self.cookie_file_path))
        fallback_auth = adapter.get_auth_config(settings={"browser_cookies": "custom_file"})
        self.assertTrue(fallback_auth.is_active)
        self.assertEqual(Path(fallback_auth.cookie_file).resolve(), self.cookie_file_path.resolve())

    # -------------------------------------------------------------------------
    # 6. Malformed and expired cookie files produce appropriate diagnostic messages
    # -------------------------------------------------------------------------
    def test_6_malformed_and_expired_cookies_diagnostic_messages(self):
        """
        Verify that malformed files fail at parsing with COOKIE_FILE_INVALID,
        and expired cookies fail at live request with AUTHENTICATION_REQUIRED.
        """
        # Malformed file
        bad_file = Path(self.temp_dir.name) / "corrupt.txt"
        bad_file.write_text("NOT A COOKIE FILE AT ALL\nrandom binary junk: \x00\x01\x02", encoding="utf-8")

        res_bad = AuthChecker.test_authentication("custom_file", custom_cookie_path=str(bad_file))
        self.assertFalse(res_bad.success)
        self.assertEqual(res_bad.stage, AuthStage.COOKIE_DECRYPTION)
        self.assertEqual(res_bad.status_code, AuthStatusCode.COOKIE_FILE_INVALID)
        self.assertIn("not a valid Netscape-format", res_bad.reason)

        # Expired session cookies file
        expired_msg = "YouTube rejected login: HTTP Error 401: Unauthorized (session expired)"
        with patch.object(AuthChecker, "_verify_live_request", return_value=(False, expired_msg)):
            res_exp = AuthChecker.test_authentication("custom_file", custom_cookie_path=str(self.cookie_file_path))
            self.assertFalse(res_exp.success)
            self.assertEqual(res_exp.stage, AuthStage.YOUTUBE_REQUEST)
            self.assertEqual(res_exp.status_code, AuthStatusCode.AUTHENTICATION_REQUIRED)
            self.assertIn("rejected the authenticated request", res_exp.reason)
            self.assertIn("Re-export fresh cookies", res_exp.suggested_action)

    # -------------------------------------------------------------------------
    # 7. Public YouTube downloads remain usable without cookies
    # -------------------------------------------------------------------------
    def test_7_public_youtube_downloads_usable_without_cookies(self):
        """
        Verify that when authentication is not configured, public YouTube downloads
        do not inject cookiefile or cookiesfrombrowser options and proceed cleanly.
        """
        settings = DownloadSettings()
        settings.auth_method = "none"
        settings.browser_cookies = "none"
        settings.custom_cookie_file = ""

        ydl_opts = YtDlpEngine.build_base_ydl_opts(settings=settings)
        self.assertNotIn("cookiefile", ydl_opts)
        self.assertNotIn("cookiesfrombrowser", ydl_opts)

        auth_config = YouTubeAdapter().get_auth_config(settings=settings)
        self.assertFalse(auth_config.is_active)
        self.assertEqual(auth_config.auth_method, "none")

    # -------------------------------------------------------------------------
    # 8. Existing HTTP 403 recovery and queue continuation remain functional
    # -------------------------------------------------------------------------
    def test_8_http_403_recovery_and_queue_continuation(self):
        """
        Verify that HTTP 403 Forbidden errors are classified as HTTP_403,
        fail cleanly without stalling the queue, and are not conflated with auth rejections.
        """
        err_msg = "HTTP Error 403: Forbidden - token expired or rate limited"
        classified = ErrorClassifier.classify(err_msg, platform="youtube")
        self.assertEqual(classified.category, ErrorCategory.HTTP_403)
        self.assertFalse(classified.retryable)
        self.assertEqual(classified.http_status, 403)
        self.assertIn("queue will automatically proceed", classified.suggested_action)
        self.assertFalse(ErrorClassifier.is_private_video(err_msg))
        self.assertFalse(ErrorClassifier.is_unavailable_video(err_msg))

    # -------------------------------------------------------------------------
    # 9. TikTok behavior remains unchanged and Douyin remains frozen
    # -------------------------------------------------------------------------
    def test_9_tiktok_unchanged_and_douyin_remains_frozen(self):
        """
        Verify that:
        - TikTok platform adapter functions normally and reports availability.
        - Douyin remains frozen/disabled in PlatformRegistry and cannot be scheduled for downloads.
        """
        # TikTok is active
        self.assertTrue(PlatformRegistry.is_available("tiktok"))
        tk_adapter = PlatformRegistry.get_adapter("tiktok")
        self.assertIsInstance(tk_adapter, TikTokAdapter)
        tk_auth = tk_adapter.get_auth_config()
        self.assertEqual(tk_auth.auth_method, "none")

        # Douyin is strictly disabled/frozen
        self.assertFalse(PlatformRegistry.is_available("douyin"))
        dy_adapter = PlatformRegistry.get_adapter("douyin")
        self.assertIsInstance(dy_adapter, DouyinAdapter)
        self.assertFalse(dy_adapter.is_available)


if __name__ == "__main__":
    unittest.main()
